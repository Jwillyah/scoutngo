/*
 * THE US WEATHER STATIONS (ASOS/AWOS), BAKED (Batch J, Section 2: the gap watch).
 *
 * Usage:  node scripts/bake-asos-stations.mjs
 * Writes: src/data/asosStations.ts from IEM's per-state ASOS network lists:
 *         stations still reporting (archive_end null) with a four-letter ICAO
 *         id. The phone picks those along the sun's line; nothing is asked at
 *         runtime but their METARs, by id.
 */
import { writeFileSync } from 'node:fs'

const STATES = 'AL AZ AR CA CO CT DE DC FL GA ID IL IN IA KS KY LA ME MD MA MI MN MS MO MT NE NV NH NJ NM NY NC ND OH OK OR PA RI SC SD TN TX UT VT VA WA WV WI WY'.split(' ')
/* "EMPORIA-GREENSVILLE RGL AIRPORT" is said "Emporia": the town, before any dash or slash, without the airport words. */
const DROP = /\b(AIRPORT|ARPT|AIRFIELD|INTL|INTERNATIONAL|MUNI|MUNICIPAL|RGNL|RGL|REGIONAL|REGL|CO|COUNTY|FIELD|FLD|ARPT|AP|AWOS|ASOS|AIR|BASE|NAS|AFB|MEMORIAL|MEM|EXEC|EXECUTIVE)\b\.?/gi
export function townOf(name) {
  const head = name.split(/[-/_,(]/)[0].replace(DROP, ' ').replace(/\s+/g, ' ').trim() || name
  return head.toLowerCase().replace(/\b([a-z])/g, (c) => c.toUpperCase()).replace(/\bMc([a-z])/g, (_, c) => `Mc${c.toUpperCase()}`)
}
const out = new Map()
for (const st of STATES) {
  const d = await fetch(`https://mesonet.agron.iastate.edu/geojson/network/${st}_ASOS.geojson`).then((r) => r.json()).catch(() => null)
  for (const f of d?.features ?? []) {
    const id = String(f.id)
    if (f.properties.archive_end !== null || !/^[A-Z0-9]{3}$/.test(id)) continue
    const icao = `K${id}`
    out.set(icao, { id: icao, name: townOf(String(f.properties.sname).replace(/\s+/g, ' ').trim()), lat: Math.round(f.geometry.coordinates[1] * 1000) / 1000, lon: Math.round(f.geometry.coordinates[0] * 1000) / 1000 })
  }
}
const list = [...out.values()].sort((a, b) => a.id.localeCompare(b.id))
writeFileSync(
  'src/data/asosStations.ts',
  `/*
 * US WEATHER STATIONS (ASOS/AWOS) STILL REPORTING: ${list.length}, GENERATED by
 * scripts/bake-asos-stations.mjs from IEM's state networks (${new Date().toISOString().slice(0, 10)}).
 * [id, name, lat, lon]. Loaded only for the gap watch (src/core/gapWatch.ts).
 */
export const ASOS_STATIONS: readonly (readonly [string, string, number, number])[] = [
${list.map((s) => `  [${JSON.stringify(s.id)}, ${JSON.stringify(s.name)}, ${s.lat}, ${s.lon}],`).join('\n')}
]
`,
)
console.log(`${list.length} stations`)
