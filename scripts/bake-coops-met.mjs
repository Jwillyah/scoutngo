/*
 * NOAA'S COASTAL WIND STATIONS (CO-OPS met), BAKED (Batch TRUTH, Section 3).
 *
 * Usage:  node scripts/bake-coops-met.mjs
 * Writes: src/data/coopsMet.ts from CO-OPS's metadata API, every station that
 *         offers meteorological data, with its NDBC id where NDBC lists the
 *         same place (latest_obs.txt, within 1 km): "CHBV2 / 8638901". The
 *         phone picks the nearest by distance from this list; at runtime it
 *         sends only a station id (api.tidesandcurrents.noaa.gov, no key).
 */
import { writeFileSync } from 'node:fs'

const met = await fetch('https://api.tidesandcurrents.noaa.gov/mdapi/prod/webapi/stations.json?type=met').then((r) => r.json())
const ndbc = await fetch('https://www.ndbc.noaa.gov/data/latest_obs/latest_obs.txt').then((r) => r.text())
const rows = ndbc
  .split('\n')
  .filter((l) => !l.startsWith('#') && l.trim() !== '')
  .map((l) => l.trim().split(/\s+/))
  .map(([id, lat, lon]) => ({ id, lat: Number(lat), lon: Number(lon) }))
  .filter((r) => /^[A-Z]{4}\d$/.test(r.id))
const km = (a, b) => {
  const r = Math.PI / 180
  const x = Math.sin(a.lat * r) * Math.sin(b.lat * r) + Math.cos(a.lat * r) * Math.cos(b.lat * r) * Math.cos((b.lon - a.lon) * r)
  return 6371 * Math.acos(Math.min(1, x))
}
const tidy = (name) => name.replace(/\s+/g, ' ').trim()
const list = met.stations
  .map((s) => {
    const at = { lat: Math.round(Number(s.lat) * 10000) / 10000, lon: Math.round(Number(s.lng) * 10000) / 10000 }
    const twin = rows.map((r) => ({ id: r.id, d: km(at, r) })).sort((a, b) => a.d - b.d)[0]
    return { id: String(s.id), ndbc: twin !== undefined && twin.d <= 1 ? twin.id : null, name: tidy(String(s.name)), ...at }
  })
  .filter((s) => Number.isFinite(s.lat) && Number.isFinite(s.lon))
  .sort((a, b) => a.id.localeCompare(b.id))
writeFileSync(
  'src/data/coopsMet.ts',
  `/*
 * NOAA CO-OPS STATIONS WITH WIND: ${list.length}, GENERATED by
 * scripts/bake-coops-met.mjs (${new Date().toISOString().slice(0, 10)}).
 * [CO-OPS id, NDBC id or null, name, lat, lon].
 */
export const COOPS_MET: readonly (readonly [string, string | null, string, number, number])[] = [
${list.map((s) => `  [${JSON.stringify(s.id)}, ${JSON.stringify(s.ndbc)}, ${JSON.stringify(s.name)}, ${s.lat}, ${s.lon}],`).join('\n')}
]
`,
)
console.log(`${list.length} stations, ${list.filter((s) => s.ndbc !== null).length} with an NDBC id`)
