/*
 * NOAA'S COASTAL STATIONS THAT MEASURE THE WATER'S TEMPERATURE, BAKED (Batch
 * FIX, Section 4).
 *
 * Usage:  node scripts/bake-coops-water-temp.mjs [stations.json]
 * Writes: src/data/coopsWaterTemp.ts from CO-OPS's metadata API, every station
 *         listed with water temperature (type=watertemp). With a file given,
 *         that saved copy of the same answer is read instead of asking.
 *         The phone picks the nearest by distance from this list; at runtime
 *         it sends only a station id (api.tidesandcurrents.noaa.gov, no key).
 */
import { readFileSync, writeFileSync } from 'node:fs'

const URL_ = 'https://api.tidesandcurrents.noaa.gov/mdapi/prod/webapi/stations.json?type=watertemp'
const body = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], 'utf8')) : await fetch(URL_).then((r) => r.json())
const tidy = (name) => name.replace(/\s+/g, ' ').trim()
const list = body.stations
  .map((s) => ({ id: String(s.id), name: tidy(String(s.name)), lat: Math.round(Number(s.lat) * 10000) / 10000, lon: Math.round(Number(s.lng) * 10000) / 10000 }))
  .filter((s) => Number.isFinite(s.lat) && Number.isFinite(s.lon))
  .sort((a, b) => a.id.localeCompare(b.id))
writeFileSync(
  'src/data/coopsWaterTemp.ts',
  `/*
 * NOAA CO-OPS STATIONS WITH WATER TEMPERATURE: ${list.length}, GENERATED by
 * scripts/bake-coops-water-temp.mjs (${new Date().toISOString().slice(0, 10)}).
 * [CO-OPS id, name, lat, lon]. Do not edit by hand; re-bake.
 */
export const COOPS_WATER_TEMP: readonly (readonly [string, string, number, number])[] = [
${list.map((s) => `  [${JSON.stringify(s.id)}, ${JSON.stringify(s.name)}, ${s.lat}, ${s.lon}],`).join('\n')}
]
`,
)
console.log(`${list.length} stations`)
