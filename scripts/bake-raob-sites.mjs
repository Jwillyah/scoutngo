/*
 * THE US SOUNDING SITES, BAKED (Batch J, Section 1).
 *
 * Usage:  node scripts/bake-raob-sites.mjs
 * Writes: src/data/raobSites.ts from IEM's RAOB network list, the sites that
 *         are online and still launching (archive_end null), US only. The
 *         phone picks the nearest; nothing is asked at runtime but the profile.
 */
import { writeFileSync } from 'node:fs'

const SRC = 'https://mesonet.agron.iastate.edu/geojson/network/RAOB.geojson'
const d = await fetch(SRC).then((r) => r.json())
const sites = d.features
  .filter((f) => f.properties.online && f.properties.archive_end === null && f.properties.country === 'US' && /^[KP][A-Z0-9]{3}$/.test(f.properties.sid))
  .map((f) => ({ id: f.properties.sid, name: f.properties.sname.replace(/\s+[A-Z]{2}\/US$/, '').replace(/\s+/g, ' ').trim(), lat: f.geometry.coordinates[1], lon: f.geometry.coordinates[0] }))
  .sort((a, b) => a.id.localeCompare(b.id))
const body = `/*
 * US SOUNDING SITES: ${sites.length}, GENERATED by scripts/bake-raob-sites.mjs
 * from ${SRC} (${new Date().toISOString().slice(0, 10)}). Twice a day, 00 Z and 12 Z.
 */
export interface RaobSite {
  id: string
  name: string
  lat: number
  lon: number
}

export const RAOB_SITES: readonly RaobSite[] = [
${sites.map((s) => `  { id: ${JSON.stringify(s.id)}, name: ${JSON.stringify(s.name)}, lat: ${s.lat}, lon: ${s.lon} },`).join('\n')}
]
`
writeFileSync('src/data/raobSites.ts', body)
console.log(`${sites.length} sites`)
